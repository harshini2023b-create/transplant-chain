// Get all hospitals as a flat list
export function getAllHospitals() {
  const all = [];
  for (const [district, hospitals] of Object.entries(HOSPITALS_BY_DISTRICT)) {
    for (const h of hospitals) {
      all.push({ ...h, district });
    }
  }
  return all;
}

